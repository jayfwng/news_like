// 용어(또는 다른 표기) → 항목
export function buildIndex() {
  const map = new Map();
  for (const [term, aliases, def, cat] of GLOSSARY) {
    const entry = { term, aliases, def, cat };
    for (const k of [term, ...aliases]) {
      if (!map.has(k)) map.set(k, entry);
    }
  }
  return map;
}
